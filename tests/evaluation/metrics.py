"""
Evaluation Metrics Definitions - Production Grade

Defines all metric models for retrieval and answer quality evaluation.
"""

from typing import List, Dict, Any, Optional
from datetime import datetime
from pydantic import BaseModel, Field


class RetrievalMetrics(BaseModel):
    """Metrics for evaluating retrieval quality"""
    
    # Core metrics
    mrr: float = Field(
        description="Mean Reciprocal Rank - position of first relevant doc"
    )
    ndcg: float = Field(
        description="Normalized Discounted Cumulative Gain - ranking quality"
    )
    
    # Coverage metrics
    keyword_coverage: float = Field(
        description="Percentage of keywords found in top-K results"
    )
    keywords_found: int = Field(
        description="Number of expected keywords actually found"
    )
    total_keywords: int = Field(
        description="Total number of expected keywords"
    )
    
    # Context metrics (if using retrieval framework)
    context_recall: Optional[float] = Field(
        default=None,
        description="Percentage of required context retrieved"
    )
    context_precision: Optional[float] = Field(
        default=None,
        description="Percentage of retrieved context that is relevant"
    )
    
    # Additional info
    docs_retrieved: int = Field(
        description="Total number of documents retrieved"
    )
    avg_relevance_score: float = Field(
        description="Average relevance score of retrieved docs"
    )


class AnswerMetrics(BaseModel):
    """Metrics for evaluating answer quality"""
    
    # Core scoring (1-5 scale)
    accuracy: float = Field(
        ge=1, le=5,
        description="Factual correctness of the answer (1-5)"
    )
    completeness: float = Field(
        ge=1, le=5,
        description="Coverage of all needed information (1-5)"
    )
    relevance: float = Field(
        ge=1, le=5,
        description="Direct answer to the question (1-5)"
    )
    
    # Additional metrics (0-1 scale)
    faithfulness: Optional[float] = Field(
        default=None, ge=0, le=1,
        description="How faithful answer is to retrieved context"
    )
    answer_relevancy: Optional[float] = Field(
        default=None, ge=0, le=1,
        description="How relevant answer is to question"
    )
    
    # Meta info
    generation_time: Optional[float] = Field(
        default=None,
        description="Time taken to generate answer in seconds"
    )
    context_used: int = Field(
        default=0,
        description="Number of context chunks used"
    )
    
    # Feedback
    feedback: str = Field(
        description="Detailed evaluation feedback"
    )
    is_correct: bool = Field(
        description="Whether answer passes quality gates"
    )
    
    @property
    def overall_score(self) -> float:
        """Calculate weighted overall score"""
        # Weights: accuracy 40%, completeness 30%, relevance 30%
        score = (
            self.accuracy * 0.4 +
            self.completeness * 0.3 +
            self.relevance * 0.3
        )
        return round(score, 2)


class TestCaseResult(BaseModel):
    """Complete evaluation result for a single test case"""
    
    # Test info
    test_id: str = Field(description="Unique test case ID")
    question: str = Field(description="The question asked")
    category: str = Field(description="Question category")
    difficulty: str = Field(description="Question difficulty")
    
    # Execution
    generated_answer: str = Field(description="Answer generated by system")
    reference_answer: Optional[str] = Field(
        default=None,
        description="Expected correct answer"
    )
    retrieved_context: List[Dict[str, Any]] = Field(
        description="Retrieved document chunks"
    )
    
    # Results
    retrieval_metrics: RetrievalMetrics = Field(
        description="Retrieval quality metrics"
    )
    answer_metrics: AnswerMetrics = Field(
        description="Answer quality metrics"
    )
    
    # Metadata
    execution_time: float = Field(description="Total execution time in seconds")
    timestamp: datetime = Field(default_factory=datetime.utcnow)
    error_message: Optional[str] = Field(default=None)
    
    @property
    def passed_quality_gates(self) -> bool:
        """Check if result passes minimum quality thresholds"""
        return (
            self.retrieval_metrics.mrr >= 0.62 and
            self.retrieval_metrics.ndcg >= 0.62 and
            self.answer_metrics.accuracy >= 4.4
        )
    
    @property
    def status(self) -> str:
        """Get status of evaluation"""
        if self.error_message:
            return "ERROR"
        elif self.passed_quality_gates:
            return "PASS"
        else:
            return "FAIL"


class EvaluationBatchResult(BaseModel):
    """Aggregated results for batch evaluation"""
    
    # Meta
    batch_id: str = Field(description="Unique batch ID")
    total_tests: int = Field(description="Total test cases evaluated")
    passed_tests: int = Field(description="Number of tests passed")
    failed_tests: int = Field(description="Number of tests failed")
    error_tests: int = Field(description="Number of tests with errors")
    
    # Aggregated metrics
    avg_mrr: float = Field(description="Average MRR across all tests")
    avg_ndcg: float = Field(description="Average nDCG across all tests")
    avg_keyword_coverage: float = Field(description="Average keyword coverage")
    
    avg_accuracy: float = Field(description="Average accuracy score")
    avg_completeness: float = Field(description="Average completeness score")
    avg_relevance: float = Field(description="Average relevance score")
    avg_overall_score: float = Field(description="Average overall score")
    
    # By category
    category_results: Dict[str, Dict[str, float]] = Field(
        description="Metrics broken down by category"
    )
    
    # Quality gates
    quality_gates_passed: bool = Field(
        description="Whether batch passes quality requirements"
    )
    
    # Detailed results
    test_results: List[TestCaseResult] = Field(
        description="Individual test case results"
    )
    
    # Metadata
    start_time: datetime = Field(description="Batch start time")
    end_time: datetime = Field(description="Batch end time")
    duration: float = Field(description="Total duration in seconds")
    
    @property
    def success_rate(self) -> float:
        """Calculate percentage of passed tests"""
        if self.total_tests == 0:
            return 0.0
        return round((self.passed_tests / self.total_tests) * 100, 2)
    
    @property
    def error_rate(self) -> float:
        """Calculate percentage of tests with errors"""
        if self.total_tests == 0:
            return 0.0
        return round((self.error_tests / self.total_tests) * 100, 2)


class BaselineComparison(BaseModel):
    """Comparison between current and baseline results"""
    
    current_results: EvaluationBatchResult
    baseline_results: EvaluationBatchResult
    
    # Metric changes (positive = improvement)
    mrr_change: float = Field(description="Change in MRR from baseline")
    ndcg_change: float = Field(description="Change in nDCG from baseline")
    accuracy_change: float = Field(description="Change in accuracy from baseline")
    completeness_change: float = Field(description="Change in completeness")
    relevance_change: float = Field(description="Change in relevance")
    
    # Status
    regression_detected: bool = Field(description="Whether significant regression detected")
    regression_threshold: float = Field(default=0.05, description="5% threshold")
    
    @property
    def has_improvement(self) -> bool:
        """Check if there's improvement vs baseline"""
        return (
            self.mrr_change > 0 and
            self.ndcg_change > 0 and
            self.accuracy_change > 0
        )
    
    @property
    def has_regression(self) -> bool:
        """Check if there's regression vs baseline"""
        return (
            self.mrr_change < -self.regression_threshold or
            self.accuracy_change < -self.regression_threshold
        )


class EvaluationReport(BaseModel):
    """Complete evaluation report for stakeholders"""
    
    # Metadata
    report_id: str
    generated_at: datetime = Field(default_factory=datetime.utcnow)
    evaluated_model: str
    knowledge_base_version: str
    
    # Results
    batch_results: EvaluationBatchResult
    baseline_comparison: Optional[BaselineComparison] = None
    
    # Analysis
    strengths: List[str] = Field(description="Areas performing well")
    weaknesses: List[str] = Field(description="Areas needing improvement")
    recommendations: List[str] = Field(description="Specific improvement recommendations")
    
    # Quality assessment
    overall_quality: str = Field(description="EXCELLENT/GOOD/ACCEPTABLE/POOR")
    ready_for_deployment: bool = Field(description="Whether ready for production")
    
    # Additional notes
    notes: Optional[str] = Field(default=None)
    reviewer: Optional[str] = Field(default=None)
